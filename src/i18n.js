function normalizeLanguage(value) {
  return value === 'id' ? 'id' : 'en';
}

function normalizeCurrency(value) {
  return value === 'IDR' ? 'IDR' : 'USD';
}

function messagesFor(lang) {
  return MESSAGES[normalizeLanguage(lang)];
}

function interpolate(value, vars = {}) {
  return String(value).replace(/\{(\w+)\}/g, (_, key) => (vars[key] ?? ''));
}

function translator(lang) {
  const dict = messagesFor(lang);
  return function t(path, vars = {}) {
    let current = dict;
    for (const segment of path.split('.')) {
      if (current == null) return path;
      current = current[segment];
    }
    if (typeof current === 'string') return interpolate(current, vars);
    return current ?? path;
  };
}

function formatUsdCents(cents) {
  const amount = Number(cents || 0) / 100;
  return new Intl.NumberFormat('en-US', {
    style: 'currency',
    currency: 'USD',
    minimumFractionDigits: Number.isInteger(amount) ? 0 : 2,
    maximumFractionDigits: 2
  }).format(amount);
}

function formatIdr(cents, rate) {
  const idr = Math.round((Number(cents || 0) / 100) * Number(rate || 0));
  return new Intl.NumberFormat('id-ID', {
    style: 'currency',
    currency: 'IDR',
    maximumFractionDigits: 0
  }).format(idr);
}

function formatMoney(cents, currency, rate) {
  return currency === 'IDR' ? formatIdr(cents, rate) : formatUsdCents(cents);
}

